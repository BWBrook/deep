"""Render the exact S/E comparison at the original sixteen design cases.

uv run --python 3.12 --with matplotlib python synthesis/plot_class_identification.py
"""
from fractions import Fraction as F
from hashlib import sha256
import itertools
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DATA = ROOT / "ideation" / "b_screen"
OUT = HERE / "figures"
KEYS = ("q", "e0", "e1", "c")


def classification(a, b):
    if a > 0:
        return "R"
    if b < 0:
        return "C"
    if a < 0 < b:
        return "both"
    return "tie / unresolved"


def deterministic_choice(a,b):
    regret_r,regret_c = max(F(0),-a),max(F(0),b)
    return "R" if regret_r<regret_c else "C" if regret_c<regret_r else "tie"


def lottery_probability_r(a,b):
    return F(1) if a>0 else F(0) if b<0 else b/(b-a)


def read_cases():
    scalar = json.loads((DATA / "n4_boundary_results.json").read_text())
    exchangeable = json.loads((DATA / "exchangeable_certificate.json").read_text())
    assert exchangeable["n"] == 4 and exchangeable["T"] == 50 and exchangeable["p"] == "1/10"
    for name, digest in exchangeable["metadata"]["source_sha256"].items():
        assert sha256((DATA/name).read_bytes()).hexdigest() == digest, name
    scalar_by_key = {tuple(F(r[k]) for k in KEYS): r for r in scalar["cases"]}
    cases = []
    for row in exchangeable["cases"]:
        key = tuple(F(row[k]) for k in KEYS)
        s = scalar_by_key[key]["whole_class"]["Delta"]
        e = row["E_class"]
        sa, sb = F(s["min_certificate"]["attained"]), F(s["max_certificate"]["attained"])
        ea, eb = F(e["a_E"]["attained"]), F(e["b_E"]["attained"])
        assert F(s["min_certificate"]["outer"]) == sa and F(s["max_certificate"]["outer"]) == sb
        assert F(e["a_E"]["outer"]) == ea and F(e["b_E"]["outer"]) == eb
        assert ea <= sa <= sb <= eb
        assert deterministic_choice(sa,sb) == deterministic_choice(ea,eb)
        cases.append({"key": key, "S": (sa,sb), "E": (ea,eb),
                      "S_choice": classification(sa,sb), "E_choice": classification(ea,eb)})
    expected = set(itertools.product((F(3,100),F(3,50)),(F(1,50),F(1,10)),(F(1,2),F(9,10)),(F(1,50),F(1,10))))
    assert {r["key"] for r in cases} == expected and len(cases) == 16
    return sorted(cases,key=lambda r:r["key"])


def write_table(cases):
    lines = [
        "# Certified action-ranking ranges: scalar and finite-exchangeable classes",
        "",
        "Generated by `plot_class_identification.py` from the exact certificate files.",
        "n=4, p=.1, T=50 model steps; the original R,C packages. S denotes scalar",
        "conditional-iid mixtures; E denotes all symmetric four-patch hit laws with",
        "the same pairwise tables. Delta=P_R-P_C. R/C means that action wins",
        "throughout the class; 'both' means compatible laws give opposite rankings.",
        "All attained and outer bounds coincide exactly. Values below are rounded",
        "to five decimal places in **percentage points**, not outward enclosures.",
        "These design counts are not ecological frequencies. Identified E cases",
        "remain unresolved in the larger labelled class L.",
        "The best deterministic minimax action is unchanged between S and E in",
        "all 16 cases; its worst-case guarantee changes. This statement concerns",
        "minimax regret over the prescribed actions, not their ranking under every law.",
        "",
        "| q | e0 | e1 | c | S: Delta range (pp) | E: Delta range (pp) | S | E |",
        "|---:|---:|---:|---:|---|---|:---:|:---:|",
    ]
    for row in cases:
        pars = " | ".join(f"{float(v):.2f}" for v in row["key"])
        ranges = " | ".join(f"[{float(100*a):+.5f}, {float(100*b):+.5f}]" for a,b in (row["S"],row["E"]))
        lines.append(f"| {pars} | {ranges} | {row['S_choice']} | {row['E_choice']} |")
    lines += ["", "## Exact minimax results at the two ambiguous E cases", "",
              "Here e0=.02, e1=.90, c=.10. Regret is loss of persistence relative",
              "to the better prescribed action under the true law. A lottery is",
              "drawn once between the two complete actions, not at each model step.", "",
              "| q | Best deterministic action (S and E) | S regret (pp) | E regret (pp) | E lottery regret (pp) | S lottery Pr(R) | E lottery Pr(R) |",
              "|---:|:---:|---:|---:|---:|---:|---:|"]
    for row in cases:
        if row["E_choice"] != "both":
            continue
        sa,sb = row["S"]; ea,eb = row["E"]
        sr = max(F(0),min(-sa,sb)); er = min(-ea,eb)
        lottery = -ea*eb/(eb-ea); prob_r = eb/(eb-ea)
        lines.append(f"| {float(row['key'][0]):.2f} | {deterministic_choice(ea,eb)} | {float(100*sr):.5f} | {float(100*er):.5f} | {float(100*lottery):.5f} | {float(lottery_probability_r(sa,sb)):.5f} | {float(prob_r):.5f} |")
    lines += ["", "Sources: [E certificate](../ideation/b_screen/exchangeable_certificate.json),",
              "[scalar certificate](../ideation/b_screen/n4_boundary_results.json),",
              "[independent audit](../ideation/b_screen/exchangeable_certificate_audit.md).", ""]
    (HERE / "class_identification_table.md").write_text("\n".join(lines))


def plot(cases):
    OUT.mkdir(exist_ok=True)
    plt.rcParams.update({"font.size":10, "axes.spines.top":False, "axes.spines.right":False})
    fig,axes = plt.subplots(1,2,figsize=(12,6.8),sharex=True,sharey=True)
    colors = {"S":"#287ca7", "E":"#575757"}
    rows = [r for r in cases if r["key"][0] == F(3,100)]
    ylabels = [f"{float(r['key'][1]):.2f}   {float(r['key'][2]):.2f}   {float(r['key'][3]):.2f}" for r in rows]
    for ax,q in zip(axes,(F(3,100),F(3,50))):
        group = [r for r in cases if r["key"][0] == q]
        for y,row in enumerate(group):
            if row["S_choice"] != row["E_choice"]:
                ax.axhspan(y-.42,y+.42,color="#faead5",zorder=0)
                ax.text(-33,y,"R → both",va="center",color="#954a00",fontsize=10,weight="bold")
            for name,offset in (("S",-.12),("E",.12)):
                a,b = row[name]
                ax.plot([float(100*a),float(100*b)],[y+offset,y+offset],
                        color=colors[name],lw=2.3,marker="|",ms=8,mew=1.5,solid_capstyle="butt")
        ax.axvline(0,color="#777777",lw=.8,ls="--",zorder=0)
        ax.set_title(f"q = {float(q):.2f}",pad=12)
        ax.set_xlim(-34,13)
        ax.set_ylim(7.6,-.6)
        ax.set_yticks(range(8),ylabels)
        ax.grid(axis="x",color="#eeeeee",lw=.7)
        ax.set_axisbelow(True)
        ax.set_xlabel(r"Persistence difference $\Delta=P_R-P_C$ (percentage points)")
        ax.text(0,.99,"C preferred",transform=ax.transAxes,va="top",fontsize=9,color="#555555")
        ax.text(1,.99,"R preferred",transform=ax.transAxes,ha="right",va="top",fontsize=9,color="#555555")
    axes[0].set_ylabel("e₀       e₁       c",rotation=0,labelpad=41,va="bottom")
    axes[0].yaxis.set_label_coords(-.20,1.01)
    handles = [Line2D([],[],color=colors[n],lw=2.5,marker="|",label=label)
               for n,label in (("S","S: scalar-hazard mixtures"),("E","E: all symmetric hit laws"))]
    fig.legend(handles=handles,loc="lower center",bbox_to_anchor=(.57,.055),ncol=2,frameon=False)
    fig.suptitle("Dependence assumptions change what pairwise shock information identifies",fontsize=14,y=.97)
    fig.text(.56,.91,"Exact ranges at 16 prescribed cases · n = 4, p = 0.10, T = 50 model steps",ha="center",fontsize=10)
    fig.text(.56,.034,"Highlighted case: a uniformly preferred action under S becomes law-dependent under E.",ha="center",fontsize=9)
    fig.text(.56,.012,"The deterministic minimax action remains the same in all 16 cases; its guarantee changes.",ha="center",fontsize=9)
    fig.subplots_adjust(left=.16,right=.98,top=.83,bottom=.18,wspace=.12)
    for suffix in ("png","pdf"):
        fig.savefig(OUT/f"class_identification.{suffix}",dpi=220)
    plt.close(fig)


def main():
    cases = read_cases()
    write_table(cases)
    plot(cases)
    print("Rendered 16 exact S/E ranges and two minimax rows.")


if __name__ == "__main__":
    main()
